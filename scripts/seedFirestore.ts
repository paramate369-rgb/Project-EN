import { initializeApp } from 'firebase/app';
import { getFirestore, collection, doc, writeBatch, getDocs } from 'firebase/firestore';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import Papa from 'papaparse';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Read Firebase config
const configPath = path.resolve(__dirname, '../firebase-applet-config.json');
const firebaseConfig = JSON.parse(fs.readFileSync(configPath, 'utf-8'));

console.log('Connecting to Firebase Project:', firebaseConfig.projectId);
console.log('Firestore Database ID:', firebaseConfig.firestoreDatabaseId);

const app = initializeApp(firebaseConfig);
const db = getFirestore(app, firebaseConfig.firestoreDatabaseId);

// Read CSV data
const csvPath = path.resolve(__dirname, '../public/assets/aistudio/Project_dashboard_cdfa4831');
let csvContent = '';
if (fs.existsSync(csvPath)) {
  csvContent = fs.readFileSync(csvPath, 'utf-8');
} else {
  console.error('CSV path not found:', csvPath);
  process.exit(1);
}

const parsed = Papa.parse(csvContent, { header: true, skipEmptyLines: true });

function parsePrice(value: any): number {
  if (typeof value === 'number') return isNaN(value) ? 0 : value;
  const str = String(value ?? '').replace(/[฿$€,\s]/g, '').trim();
  const num = parseFloat(str);
  return isNaN(num) ? 0 : num;
}

function generateDocId(name: string, project: string, index: number): string {
  const cleanName = name.replace(/[^a-zA-Z0-9ก-๙]/g, '').slice(0, 20) || 'user';
  const cleanProj = project.replace(/[^a-zA-Z0-9ก-๙]/g, '').slice(0, 30) || 'proj';
  return `p_${cleanName}_${cleanProj}_${index + 1}`.slice(0, 64);
}

async function seed() {
  const rawRows: any[] = parsed.data;
  let lastEmployeeId = '';
  let lastEmployeeName = '';
  let lastEmployeeRole = '';

  const cleanProjects: Array<{
    id: string;
    name: string;
    role: string;
    project: string;
    price: number;
    status: string;
  }> = [];

  for (let i = 0; i < rawRows.length; i++) {
    const row = rawRows[i];
    if (!row || typeof row !== 'object') continue;
    const rowStr = Object.values(row).join(' ').trim();
    if (!rowStr || rowStr.toLowerCase().includes('generated by')) continue;

    const findKey = (candidates: string[]) => {
      const keys = Object.keys(row);
      for (const cand of candidates) {
        const found = keys.find(k => k.trim().toLowerCase() === cand.toLowerCase());
        if (found && row[found] !== undefined && String(row[found]).trim() !== '') {
          return String(row[found]).trim();
        }
      }
      return '';
    };

    let rawId = findKey(['EmployeeID', 'รหัสพนักงาน', 'รหัส', 'ID']);
    let rawName = findKey(['ชื่อพนักงาน', 'ชื่อ', 'EmployeeName', 'Name']);
    let rawRole = findKey(['ตำแหน่ง', 'Position', 'Role']);
    const rawProject = findKey(['ชื่อโครงการ', 'โครงการ', 'Project', 'ProjectName']);
    const rawPrice = findKey(['ยอดราคา', 'ราคา', 'มูลค่า', 'Price', 'Amount', 'Budget']);
    const rawStatus = findKey(['สถานะ', 'Status']);

    if (!rawProject && !rawName && !rawPrice) continue;

    if (rawName) {
      lastEmployeeName = rawName;
    } else if (lastEmployeeName) {
      rawName = lastEmployeeName;
    }

    if (rawId) {
      lastEmployeeId = rawId;
    } else if (lastEmployeeId && rawName === lastEmployeeName) {
      rawId = lastEmployeeId;
    } else {
      rawId = `E${i + 1}`;
    }

    if (rawRole) {
      lastEmployeeRole = rawRole;
    } else if (lastEmployeeRole && rawName === lastEmployeeName) {
      rawRole = lastEmployeeRole;
    } else {
      rawRole = 'Project Engineer';
    }

    cleanProjects.push({
      id: rawId,
      name: rawName,
      role: rawRole,
      project: rawProject,
      price: parsePrice(rawPrice),
      status: rawStatus || 'กำลังดำเนินการ',
    });
  }

  console.log(`Parsed ${cleanProjects.length} projects to save in Firestore:`);
  cleanProjects.forEach((p, idx) => {
    console.log(` ${idx + 1}. [${p.id}] ${p.name} (${p.role}) -> ${p.project}: ${p.price} THB [${p.status}]`);
  });

  const batch = writeBatch(db);
  const colRef = collection(db, 'projects');

  // Clear previous docs if any to ensure clean fresh sync
  const existingDocs = await getDocs(colRef);
  console.log(`Found ${existingDocs.size} existing docs in Firestore, updating...`);
  existingDocs.forEach(d => {
    batch.delete(d.ref);
  });

  cleanProjects.forEach((p, index) => {
    const docId = generateDocId(p.name, p.project, index);
    const docRef = doc(db, 'projects', docId);
    batch.set(docRef, {
      ...p,
      updatedAt: new Date().toISOString(),
    });
  });

  await batch.commit();
  console.log('Successfully written all projects to Firestore in project wlprojectsum!');
  process.exit(0);
}

seed().catch(err => {
  console.error('Error seeding Firestore:', err);
  process.exit(1);
});
