const INITIAL_STATS: DashboardStats = {
  totalEmployees: 0,
  totalProjects: 0,
  totalAssignments: 0,
  totalValue: 0,
  statusCounts: {
    ongoing: 0,
    completed: 0,
    proposal: 0,
  },
};

function convertToGoogleSheetCsvUrl(rawUrl: string): string {
  if (!rawUrl || !rawUrl.trim()) return '';
  const trimmed = rawUrl.trim();
  if (trimmed.includes('output=csv') || trimmed.includes('export?format=csv') || trimmed.includes('tqx=out:csv')) {
    return trimmed;
  }
  const match = trimmed.match(/\/spreadsheets\/d\/([a-zA-Z0-9-_]+)/);
  if (match && match[1]) {
    const sheetId = match[1];
    const gidMatch = trimmed.match(/[#&?]gid=([0-9]+)/);
    const gidParam = gidMatch ? `&gid=${gidMatch[1]}` : '';
    return `https://docs.google.com/spreadsheets/d/${sheetId}/export?format=csv${gidParam}`;
  }
  return trimmed;
}

function parsePrice(value: any): number {
  if (typeof value === 'number') return isNaN(value) ? 0 : value;
  const str = String(value ?? '').replace(/[฿$€,\s]/g, '').trim();
  const num = parseFloat(str);
  return isNaN(num) ? 0 : num;
}

export default function App() {
  const [rows, setRows] = useState<ProjectItem[]>(() => INITIAL_FALLBACK_PROJECTS);
  const [employees, setEmployees] = useState<Employee[]>(() => {
    return computeStatsAndEmployees(INITIAL_FALLBACK_PROJECTS).employees;
  });
  const [stats, setStats] = useState<DashboardStats>(() => {
    return computeStatsAndEmployees(INITIAL_FALLBACK_PROJECTS).stats;
  });
  const [source, setSource] = useState<'google_sheets' | 'local_file'>('local_file');
  const [lastUpdated, setLastUpdated] = useState<string>(new Date().toISOString());
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [isFetching, setIsFetching] = useState<boolean>(false);
  const [selectedEmployeeName, setSelectedEmployeeName] = useState<string | null>(null);
  const [statusFilter, setStatusFilter] = useState<string>('all');
  const [searchQuery, setSearchQuery] = useState<string>('');

  // Firestore Synced Settings
  const [sheetUrl, setSheetUrl] = useState<string>('');
  const [syncInterval, setSyncInterval] = useState<number>(15);
  const [isAutoSyncEnabled, setIsAutoSyncEnabled] = useState<boolean>(true);

  const [countdown, setCountdown] = useState<number>(15);
  const [isSettingsOpen, setIsSettingsOpen] = useState<boolean>(false);
  const [toastMessage, setToastMessage] = useState<{ text: string; type: 'success' | 'error' } | null>(null);

  const countdownTimerRef = useRef<NodeJS.Timeout | null>(null);
  const isFetchingRef = useRef<boolean>(false);

  const showToast = (text: string, type: 'success' | 'error' = 'success') => {
    setToastMessage({ text, type });
    setTimeout(() => {
      setToastMessage(null);
    }, 4000);
  };

  // Helper to recompute and set state from project rows
  const applyProjectRows = useCallback((newRows: ProjectItem[]) => {
    if (!newRows || newRows.length === 0) return;
    setRows(newRows);
    const { employees: newEmps, stats: newStats } = computeStatsAndEmployees(newRows);
    setEmployees(newEmps);
    setStats(newStats);
  }, []);

  // Parse raw rows from Google Sheets CSV
  const parseCsvIntoProjects = (csvText: string): ProjectItem[] => {
    const parsed = Papa.parse(csvText, { header: true, skipEmptyLines: true });
    const rawRows: any[] = parsed.data;
    let lastEmployeeId = '';
    let lastEmployeeName = '';
    let lastEmployeeRole = '';
    const cleanProjects: ProjectItem[] = [];

    for (let i = 0; i < rawRows.length; i++) {
      const row = rawRows[i];
      if (!row || typeof row !== 'object') continue;
      const rowStr = Object.values(row).join(' ').trim();
      if (!rowStr || rowStr.toLowerCase().includes('generated by')) continue;

      const findKey = (candidates: string[]) => {
        const keys = Object.keys(row);
        for (const cand of candidates) {
          const found = keys.find(k => k.trim().toLowerCase() === cand.toLowerCase());
          if (found && row[found] !== undefined && String(row[found]).trim() !== '') {
            return String(row[found]).trim();
          }
        }
        return '';
      };

      let rawId = findKey(['EmployeeID', 'รหัสพนักงาน', 'รหัส', 'ID']);
      let rawName = findKey(['ชื่อพนักงาน', 'ชื่อ', 'EmployeeName', 'Name']);
      let rawRole = findKey(['ตำแหน่ง', 'Position', 'Role']);
      const rawProject = findKey(['ชื่อโครงการ', 'โครงการ', 'Project', 'ProjectName']);
      const rawPrice = findKey(['ยอดราคา', 'ราคา', 'มูลค่า', 'Price', 'Amount', 'Budget']);
      const rawStatus = findKey(['สถานะ', 'Status']);

      if (!rawProject && !rawName && !rawPrice) continue;

      if (rawName) {
        lastEmployeeName = rawName;
      } else if (lastEmployeeName) {
        rawName = lastEmployeeName;
      }

      if (rawId) {
        lastEmployeeId = rawId;
      } else if (lastEmployeeId && rawName === lastEmployeeName) {
        rawId = lastEmployeeId;
      } else {
        rawId = `E${i + 1}`;
      }

      if (rawRole) {
        lastEmployeeRole = rawRole;
      } else if (lastEmployeeRole && rawName === lastEmployeeName) {
        rawRole = lastEmployeeRole;
      } else {
        rawRole = 'Project Engineer';
      }

      cleanProjects.push({
        id: rawId,
        name: rawName,
        role: rawRole,
        project: rawProject,
        price: parsePrice(rawPrice),
        status: rawStatus || 'กำลังดำเนินการ',
      });
    }

    return cleanProjects;
  };

  // Main data fetch & sync function
  const fetchLatestData = useCallback(
    async (targetSheetUrl?: string, isManual = false): Promise<boolean> => {
      if (isFetchingRef.current) return true;
      isFetchingRef.current = true;
      setIsFetching(true);

      const activeUrl = targetSheetUrl !== undefined ? targetSheetUrl : sheetUrl;
      let fetchedFresh = false;

      // 1. If Google Sheet URL is provided, try fetching Google Sheets first
      if (activeUrl && activeUrl.trim()) {
        try {
          const csvExportUrl = convertToGoogleSheetCsvUrl(activeUrl);
          const response = await fetch(csvExportUrl, {
            headers: { Accept: 'text/csv, text/plain, */*' },
            signal: AbortSignal.timeout(7000),
          });

          if (response.ok) {
            const text = await response.text();
            const sheetProjects = parseCsvIntoProjects(text);
            if (sheetProjects.length > 0) {
              setSource('google_sheets');
              setLastUpdated(new Date().toISOString());
              setErrorMessage(null);
              applyProjectRows(sheetProjects);
              await syncProjectsToFirestore(sheetProjects);
              fetchedFresh = true;
            }
          }
        } catch (sheetErr) {
          console.warn('Google Sheet fetch error:', sheetErr);
        }

        // Try backend proxy as second attempt if client fetch failed
        if (!fetchedFresh) {
          try {
            const queryParams = new URLSearchParams();
            queryParams.set('sheetUrl', activeUrl);
            const res = await fetch(`/api/dashboard?${queryParams.toString()}`, {
              signal: AbortSignal.timeout(5000),
            });
            if (res.ok) {
              const json: DashboardApiResponse = await res.json();
              if (json.success && json.rawRows && json.rawRows.length > 0) {
                setSource(json.source);
                setLastUpdated(json.lastUpdated || new Date().toISOString());
                setErrorMessage(json.errorMessage || null);
                applyProjectRows(json.rawRows);
                await syncProjectsToFirestore(json.rawRows);
                fetchedFresh = true;
              }
            }
          } catch (proxyErr) {
            console.warn('Proxy fetch error:', proxyErr);
          }
        }
      }

      // 2. Fetch directly from Firebase Firestore in wlprojectsum
      if (!fetchedFresh) {
        try {
          const firestoreProjects = await getProjectsFromFirestore();
          if (firestoreProjects && firestoreProjects.length > 0) {
            applyProjectRows(firestoreProjects);
            setLastUpdated(new Date().toISOString());
            setErrorMessage(null);
            fetchedFresh = true;
          }
        } catch (fsErr) {
          console.warn('Direct Firestore fetch error:', fsErr);
        }
      }

      // 3. Fallback to initial seed projects if still empty
      if (!fetchedFresh && rows.length === 0) {
        applyProjectRows(INITIAL_FALLBACK_PROJECTS);
        syncProjectsToFirestore(INITIAL_FALLBACK_PROJECTS).catch(console.error);
        fetchedFresh = true;
      }

      setIsFetching(false);
      isFetchingRef.current = false;
      setCountdown(syncInterval);

      if (isManual) {
        if (fetchedFresh) {
          showToast('อัปเดตข้อมูลสดเรียบร้อยแล้ว', 'success');
        } else {
          showToast('ไม่สามารถเชื่อมต่อเพื่อดึงข้อมูลสดได้ กำลังแสดงข้อมูลที่มีอยู่', 'error');
        }
      }

      return fetchedFresh;
    },
    [sheetUrl, syncInterval, rows.length, applyProjectRows]
  );

  // Firestore Real-time subscriptions & Initial Bootstrap
  useEffect(() => {
    testFirestoreConnection();

    // 1. Subscribe to Firestore settings
    const unsubSettings = subscribeToSettings((settings) => {
      if (settings.sheetUrl !== undefined) {
        setSheetUrl(settings.sheetUrl);
      }
      if (settings.syncInterval) {
        setSyncInterval(settings.syncInterval);
      }
      if (settings.lastUpdated) {
        setLastUpdated(settings.lastUpdated);
      }
    });

    // 2. Subscribe to Firestore projects collection in real time
    const unsubProjects = subscribeToProjects(
      (firestoreProjects) => {
        if (firestoreProjects && firestoreProjects.length > 0) {
          applyProjectRows(firestoreProjects);
        } else {
          // If Firestore is empty, seed it with the 13 projects
          syncProjectsToFirestore(INITIAL_FALLBACK_PROJECTS);
          applyProjectRows(INITIAL_FALLBACK_PROJECTS);
        }
      },
      (error) => {
        console.warn('Firestore subscription fallback:', error);
      }
    );

    return () => {
      unsubSettings();
      unsubProjects();
    };
  }, [applyProjectRows]);

  // Real-time Countdown & Polling Loop
  useEffect(() => {
    if (!isAutoSyncEnabled) {
      if (countdownTimerRef.current) clearInterval(countdownTimerRef.current);
      return;
    }

    setCountdown(syncInterval);

    countdownTimerRef.current = setInterval(() => {
      setCountdown((prev) => {
        if (prev <= 1) {
          // Trigger quiet background refresh (isManual = false)
          fetchLatestData(sheetUrl, false);
          return syncInterval;
        }
        return prev - 1;
      });
    }, 1000);

    return () => {
      if (countdownTimerRef.current) clearInterval(countdownTimerRef.current);
    };
  }, [syncInterval, isAutoSyncEnabled, sheetUrl, fetchLatestData]);

  // Save Settings from modal to Firestore
  const handleSaveSettings = async (newUrl: string, newInterval: number, newAutoSync: boolean) => {
    const success = await fetchLatestData(newUrl, true);
    setSheetUrl(newUrl);
    setSyncInterval(newInterval);
    setIsAutoSyncEnabled(newAutoSync);

    // Save settings to Firebase Firestore
    await saveSettingsToFirestore({
      sheetUrl: newUrl,
      syncInterval: newInterval,
      lastUpdated: new Date().toISOString(),
    });

    return success;
  };

  // Reset to default sample dataset in Firestore
  const handleResetToDefault = async () => {
    setSheetUrl('');
    await saveSettingsToFirestore({
      sheetUrl: '',
      lastUpdated: new Date().toISOString(),
    });
    await syncProjectsToFirestore(INITIAL_FALLBACK_PROJECTS);
    applyProjectRows(INITIAL_FALLBACK_PROJECTS);
    showToast('รีเซ็ตข้อมูลตั้งต้นบน Firebase เรียบร้อยแล้ว', 'success');
  };

  return (
    <div className="min-h-screen bg-[#f3f6fb] text-[#243247] p-4 sm:p-6 md:p-8">
      <main className="max-w-[1400px] mx-auto">
        {/* Toast Notification */}
        {toastMessage && (
          <div
            className={`fixed bottom-5 right-5 z-50 flex items-center gap-2 px-4 py-2.5 rounded-xl text-xs font-semibold shadow-lg transition-all animate-in fade-in slide-in-from-bottom-2 ${
              toastMessage.type === 'success'
                ? 'bg-slate-900 text-white'
                : 'bg-rose-600 text-white'
            }`}
          >
            {toastMessage.type === 'success' ? (
              <CheckCircle2 className="w-4 h-4 text-emerald-400" />
            ) : (
              <AlertCircle className="w-4 h-4 text-amber-300" />
            )}
            <span>{toastMessage.text}</span>
          </div>
        )}

        {/* Global Error Notice if any */}
        {errorMessage && (
          <div className="mb-4 p-3.5 bg-amber-50 border border-amber-200 rounded-xl text-xs text-amber-800 flex items-center justify-between gap-3">
            <div className="flex items-center gap-2">
              <AlertCircle className="w-4 h-4 text-amber-600 shrink-0" />
              <span>{errorMessage} (กำลังแสดงข้อมูลล่าสุดจาก Firebase)</span>
            </div>
            <button
              onClick={() => setIsSettingsOpen(true)}
              className="font-bold underline text-amber-900 hover:text-amber-950 cursor-pointer shrink-0"
            >
              แก้ไขลิงก์
            </button>
          </div>
        )}

        {/* Header with live sync status and Firebase badge */}
        <Header
          lastUpdated={lastUpdated}
          isFetching={isFetching}
          source={source}
          sheetUrl={sheetUrl}
          errorMessage={errorMessage}
          countdown={countdown}
          isAutoSyncEnabled={isAutoSyncEnabled}
          onRefreshNow={() => fetchLatestData(sheetUrl, true)}
          onOpenSettings={() => setIsSettingsOpen(true)}
        />

        {/* KPI Stats Section */}
        <StatsSection
          stats={stats}
          selectedStatusFilter={statusFilter}
          onSelectStatusFilter={(filter) => {
            setStatusFilter(filter);
          }}
        />

        {/* Office Interactive Floor Plan with Character Avatars */}
        <OfficeFloor
          employees={employees}
          selectedEmployeeName={selectedEmployeeName}
          onSelectEmployee={(name) => {
            setSelectedEmployeeName(name);
          }}
        />

        {/* Detailed Project Table */}
        <ProjectTable
          rows={rows}
          selectedEmployeeName={selectedEmployeeName}
          statusFilter={statusFilter}
          searchQuery={searchQuery}
          onSearchChange={setSearchQuery}
          onSelectEmployee={(name) => {
            setSelectedEmployeeName(name);
          }}
        />

        {/* Google Sheets Settings Modal */}
        <SheetSettingsModal
          isOpen={isSettingsOpen}
          activeSheetUrl={sheetUrl}
          syncInterval={syncInterval}
          isAutoSyncEnabled={isAutoSyncEnabled}
          onClose={() => setIsSettingsOpen(false)}
          onSave={handleSaveSettings}
          onResetToDefault={handleResetToDefault}
        />
      </main>
    </div>
  );
}
