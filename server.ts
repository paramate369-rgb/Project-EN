let activeSheetUrl: string = process.env.GOOGLE_SHEET_URL || '';
let syncIntervalSeconds: number = 15;

function convertToGoogleSheetCsvUrl(rawUrl: string): string {
  if (!rawUrl || !rawUrl.trim()) return '';
  const trimmed = rawUrl.trim();

  // If already a published CSV or export CSV link
  if (trimmed.includes('output=csv') || trimmed.includes('export?format=csv') || trimmed.includes('tqx=out:csv')) {
    return trimmed;
  }

  // If it's a standard docs.google.com/spreadsheets/d/{ID} link
  const match = trimmed.match(/\/spreadsheets\/d\/([a-zA-Z0-9-_]+)/);
  if (match && match[1]) {
    const sheetId = match[1];
    // Check if gid is present
    const gidMatch = trimmed.match(/[#&?]gid=([0-9]+)/);
    const gidParam = gidMatch ? `&gid=${gidMatch[1]}` : '';
    return `https://docs.google.com/spreadsheets/d/${sheetId}/export?format=csv${gidParam}`;
  }

  return trimmed;
}

function parsePrice(value: any): number {
  if (typeof value === 'number') return isNaN(value) ? 0 : value;
  const str = String(value ?? '').replace(/[฿$€,\s]/g, '').trim();
  const num = parseFloat(str);
  return isNaN(num) ? 0 : num;
}

function cleanAndGroupData(rawRows: any[]) {
  const cleaned: Array<{
    id: string;
    name: string;
    role: string;
    project: string;
    price: number;
    status: string;
  }> = [];

  let lastEmployeeId = '';
  let lastEmployeeName = '';
  let lastEmployeeRole = '';

  for (let i = 0; i < rawRows.length; i++) {
    const row = rawRows[i];
    if (!row || typeof row !== 'object') continue;

    // Filter out footer rows like "Generated by AI Passport"
    const rowStr = Object.values(row).join(' ').trim();
    if (!rowStr || rowStr.toLowerCase().includes('generated by')) continue;

    // Helper to find key insensitive
    const findKey = (candidates: string[]) => {
      const keys = Object.keys(row);
      for (const cand of candidates) {
        const found = keys.find(k => k.trim().toLowerCase() === cand.toLowerCase());
        if (found && row[found] !== undefined && String(row[found]).trim() !== '') {
          return String(row[found]).trim();
        }
      }
      return '';
    };

    let rawId = findKey(['EmployeeID', 'รหัสพนักงาน', 'รหัส', 'ID']);
    let rawName = findKey(['ชื่อพนักงาน', 'ชื่อ', 'EmployeeName', 'Name']);
    let rawRole = findKey(['ตำแหน่ง', 'Position', 'Role']);
    const rawProject = findKey(['ชื่อโครงการ', 'โครงการ', 'Project', 'ProjectName']);
    const rawPrice = findKey(['ยอดราคา', 'ราคา', 'มูลค่า', 'Price', 'Amount', 'Budget']);
    const rawStatus = findKey(['สถานะ', 'Status']);

    if (!rawProject && !rawName && !rawPrice) continue;

    // Handle merged/inherited row values
    if (rawName) {
      lastEmployeeName = rawName;
    } else if (lastEmployeeName) {
      rawName = lastEmployeeName;
    }

    if (rawId) {
      lastEmployeeId = rawId;
    } else if (lastEmployeeId && rawName === lastEmployeeName) {
      rawId = lastEmployeeId;
    } else {
      rawId = `E${i + 1}`;
    }

    if (rawRole) {
      lastEmployeeRole = rawRole;
    } else if (lastEmployeeRole && rawName === lastEmployeeName) {
      rawRole = lastEmployeeRole;
    } else {
      rawRole = 'ทีมงาน';
    }

    cleaned.push({
      id: rawId,
      name: rawName || 'ไม่ระบุชื่อ',
      role: rawRole,
      project: rawProject || 'ไม่ระบุชื่อโครงการ',
      price: parsePrice(rawPrice),
      status: rawStatus || 'กำลังดำเนินการ',
    });
  }

  // Group by Employee (using normalized employee name as primary anchor if id is duplicated or blank)
  const employeeMap = new Map<string, {
    id: string;
    name: string;
    role: string;
    projects: Array<{ project: string; price: number; status: string }>;
    totalValue: number;
  }>();

  for (const item of cleaned) {
    const key = item.name;
    if (!employeeMap.has(key)) {
      employeeMap.set(key, {
        id: item.id,
        name: item.name,
        role: item.role,
        projects: [],
        totalValue: 0,
      });
    }
    const emp = employeeMap.get(key)!;
    emp.projects.push({
      project: item.project,
      price: item.price,
      status: item.status,
    });
    emp.totalValue += item.price;
  }

  const employees = Array.from(employeeMap.values());

  // Calculate unique projects
  const uniqueProjects = new Map<string, { name: string; price: number; status: string; assignee: string }>();
  for (const item of cleaned) {
    if (!uniqueProjects.has(item.project)) {
      uniqueProjects.set(item.project, {
        name: item.project,
        price: item.price,
        status: item.status,
        assignee: item.name,
      });
    }
  }

  const totalValue = Array.from(uniqueProjects.values()).reduce((sum, p) => sum + p.price, 0);

  return {
    rawRows: cleaned,
    employees,
    stats: {
      totalEmployees: employees.length,
      totalProjects: uniqueProjects.size,
      totalAssignments: cleaned.length,
      totalValue,
      statusCounts: {
        ongoing: cleaned.filter(r => r.status.includes('ดำเนิน')).length,
        completed: cleaned.filter(r => r.status.includes('เสร็จ') || r.status.toLowerCase().includes('done')).length,
        proposal: cleaned.filter(r => r.status.includes('เสนอ') || r.status.toLowerCase().includes('proposal')).length,
      }
    }
  };
}

async function startServer() {
  const app = express();
  const PORT = process.env.PORT || 3000;

  app.use(express.json());

  // API to fetch real-time dashboard data
  app.get('/api/dashboard', async (req, res) => {
    const requestedUrl = (req.query.sheetUrl as string) || activeSheetUrl;
    let csvData = '';
    let source = 'local_file';
    let errorMessage = '';

    if (requestedUrl && requestedUrl.trim()) {
      const csvUrl = convertToGoogleSheetCsvUrl(requestedUrl);
      try {
        const response = await fetch(csvUrl, {
          headers: {
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) OfficeProjectDashboard/1.0',
            'Accept': 'text/csv, text/plain, */*',
          },
          signal: AbortSignal.timeout(8000),
        });

        if (response.ok) {
          csvData = await response.text();
          source = 'google_sheets';
        } else {
          errorMessage = `ไม่สามารถดึงข้อมูลจาก Google Sheets ได้ (HTTP ${response.status})`;
        }
      } catch (err: any) {
        errorMessage = `เกิดข้อผิดพลาดในการเชื่อมต่อ Google Sheets: ${err?.message || 'Timeout'}`;
      }
    }

    // Fallback to local project file if Google Sheets not configured or failed
    if (!csvData) {
      try {
        if (fs.existsSync(LOCAL_CSV_PATH)) {
          csvData = fs.readFileSync(LOCAL_CSV_PATH, 'utf-8');
        } else {
          csvData = DEFAULT_CSV_FALLBACK;
        }
      } catch {
        csvData = DEFAULT_CSV_FALLBACK;
      }
    }

    try {
      const parsed = Papa.parse(csvData, {
        header: true,
        skipEmptyLines: true,
        dynamicTyping: false,
      });

      const structured = cleanAndGroupData(parsed.data);

      return res.json({
        success: true,
        source,
        activeSheetUrl,
        lastUpdated: new Date().toISOString(),
        errorMessage: errorMessage || null,
        ...structured,
      });
    } catch (parseErr: any) {
      return res.status(500).json({
        success: false,
        error: 'Failed to parse CSV data',
        details: parseErr.message,
      });
    }
  });

  // API to update settings (e.g. Google Sheet URL, sync interval)
  app.post('/api/settings', (req, res) => {
    const { sheetUrl, interval } = req.body;
    if (typeof sheetUrl === 'string') {
      activeSheetUrl = sheetUrl.trim();
    }
    if (typeof interval === 'number' && interval >= 5) {
      syncIntervalSeconds = interval;
    }
    return res.json({
      success: true,
      activeSheetUrl,
      syncIntervalSeconds,
    });
  });

  app.get('/api/settings', (req, res) => {
    return res.json({
      activeSheetUrl,
      syncIntervalSeconds,
    });
  });

  // Setup Vite or Static serving
  if (process.env.NODE_ENV === 'production') {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  } else {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(Number(PORT), '0.0.0.0', () => {
    console.log(`Office Project Dashboard server running at http://0.0.0.0:${PORT}`);
  });
}

startServer().catch(err => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
